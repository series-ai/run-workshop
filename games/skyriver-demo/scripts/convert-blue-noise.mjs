/**
 * Converts the offline void-and-cluster tile into the app's source module.
 *
 * The generator is NumPy and never runs in the app (R23 brief). This is the one conversion step:
 * it reads the exported TypeScript array, checks it byte-for-byte against the raw .r8 input and the
 * declared SHA-256, then writes `src/render/blueNoiseTile.ts`. Re-running it is idempotent.
 *
 * Usage: node scripts/convert-blue-noise.mjs <blue-noise-data.ts.txt> <blue-noise-64.r8> <out.ts>
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const DECLARED_SHA256 = 'eacd51e51588466d345792c3105c6bb89e0ec81b30bfc26d033ce99bd6b6c602';

const [sourcePath, rawPath, outPath] = process.argv.slice(2);
if (sourcePath === undefined || rawPath === undefined || outPath === undefined) {
  throw new Error('USAGE: convert-blue-noise.mjs <data.ts.txt> <raw.r8> <out.ts>');
}

const raw = readFileSync(rawPath);
const rawSha = createHash('sha256').update(raw).digest('hex');
if (rawSha !== DECLARED_SHA256) throw new Error(`RAW_SHA_MISMATCH:${rawSha}`);

const text = readFileSync(sourcePath, 'utf8');
const width = Number(/BLUE_NOISE_WIDTH = (\d+)/.exec(text)?.[1]);
const height = Number(/BLUE_NOISE_HEIGHT = (\d+)/.exec(text)?.[1]);
const body = /BLUE_NOISE_BYTES = new Uint8Array\(\[([\s\S]*?)\]\)/.exec(text)?.[1];
if (!Number.isInteger(width) || !Number.isInteger(height) || body === undefined) {
  throw new Error('SOURCE_SHAPE_UNREADABLE');
}

const values = body.split(',').map((part) => part.trim()).filter((part) => part.length > 0).map(Number);
if (values.length !== width * height) throw new Error(`COUNT_MISMATCH:${values.length}`);
for (const value of values) {
  if (!Number.isInteger(value) || value < 0 || value > 255) throw new Error(`BYTE_RANGE:${value}`);
}

const bytes = Uint8Array.from(values);
if (bytes.length !== raw.length) throw new Error(`LENGTH_MISMATCH:${bytes.length}/${raw.length}`);
for (let i = 0; i < bytes.length; i += 1) {
  if (bytes[i] !== raw[i]) throw new Error(`BYTE_MISMATCH_AT:${i}`);
}

// A rank map: every byte value appears the same number of times. 4096 bytes over 256 values = 16.
const histogram = new Int32Array(256);
for (const value of bytes) histogram[value] += 1;
const expected = bytes.length / 256;
for (let value = 0; value < 256; value += 1) {
  if (histogram[value] !== expected) throw new Error(`HISTOGRAM_BIN:${value}=${histogram[value]}`);
}

const rows = [];
for (let y = 0; y < height; y += 1) {
  rows.push('  ' + Array.from(bytes.subarray(y * width, (y + 1) * width)).join(', ') + ',');
}

writeFileSync(outPath, `/**
 * @file blueNoiseTile.ts — the R23 blue-noise jitter tile, as drawn bytes.
 *
 * GENERATED by scripts/convert-blue-noise.mjs from the offline void-and-cluster input. Do not edit
 * by hand and do not generate at runtime: the NumPy generator never runs in the app. Re-run the
 * script to reproduce this file; it fails rather than emit a tile whose SHA-256 has moved.
 *
 * The tile is a periodic rank map: all 256 byte values appear exactly ${expected} times, and its
 * measured FFT shows low-frequency suppression (the proof is the input's own spectrum record). An
 * FFT proves spatial distribution only — it is not evidence of temporal convergence.
 */

/** SHA-256 of the ${bytes.length} raw bytes below, as declared by the offline input. */
export const SKYRIVER_BLUE_NOISE_SHA256 = '${DECLARED_SHA256}';

export const SKYRIVER_BLUE_NOISE_WIDTH = ${width};
export const SKYRIVER_BLUE_NOISE_HEIGHT = ${height};

/** Every byte value appears this many times, so the tile is a rank map and not an approximation. */
export const SKYRIVER_BLUE_NOISE_BIN_COUNT = ${expected};

export const SKYRIVER_BLUE_NOISE_BYTES: Uint8Array<ArrayBuffer> = new Uint8Array([
${rows.join('\n')}
]);

/**
 * The byte-centred jitter a sampled, normalised red channel becomes: \`r * (255/256) + 0.5/256\`.
 *
 * A raw \`r\` of 0 would place a sample exactly on its interval edge and 255/255 would place it on
 * the far edge; centring maps the 256 byte codes onto 256 half-open cell centres instead.
 */
export function skyriverBlueNoiseJitter(normalisedRed: number): number {
  return normalisedRed * (255 / 256) + 0.5 / 256;
}

/** The same jitter straight from a byte code, for the node checks. */
export function skyriverBlueNoiseJitterFromByte(byte: number): number {
  return skyriverBlueNoiseJitter(byte / 255);
}
`);

process.stdout.write(`blueNoiseTile.ts written: ${width}x${height}, ${bytes.length} bytes, sha256 ${rawSha}, all 256 bins = ${expected}\n`);
