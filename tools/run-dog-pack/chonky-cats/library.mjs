// Library build: Chonky Cats as it ships in the RUN asset library (jam-ready-assets
// run-chonky-cats/3D/characters), where a 3D pack's runtime files are its .glb files plus the
// .png / .jpg in or under a folder holding .glb files. So no JSON or CSV here (as the Hounds'
// chunky-toy/tools/library.mjs):
//   cats/<body>.glb, cats/cat-clips.glb, cats/coats/*.png   the 8 bodies, every clip, coat masks
//   wear/<body>--collar|bandana|bell_collar|neckerchief.glb, cloth-patterns.png
//   props/<prop>.glb
//   code/catclips.js, catcoat.js, catdata.js                 copied into the game's source
// Geometry is quantized + meshopt; textures stay the source JPEGs.
//
//   node chonky-cats/library.mjs      (from tools/run-dog-pack; writes chonky-cats/library/)
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { dedup, prune, quantize, resample, meshopt } from '@gltf-transform/functions';
import { MeshoptEncoder, MeshoptDecoder } from 'meshoptimizer';
import { tidyJSON } from '../../glb-tidy.mjs';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = import.meta.dirname;
const HOUNDS = path.join(ROOT, '..', 'chunky-toy');
const OUT = path.join(ROOT, 'library');

await MeshoptEncoder.ready;
await MeshoptDecoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({
  'meshopt.encoder': MeshoptEncoder, 'meshopt.decoder': MeshoptDecoder });
const QUANT = { quantizePosition: 14, quantizeNormal: 8, quantizeTexcoord: 12, quantizeWeight: 16 };
const PRUNE = prune({ keepAttributes: true, keepExtras: true, propertyTypes: ['node', 'mesh', 'primitive', 'material', 'texture', 'accessor', 'bufferView'] });
const MESHOPT = meshopt({ encoder: MeshoptEncoder, level: 'medium', ...QUANT });
let bytes = 0, files = 0;

async function glb(src, dst, kind = 'model') {
  const doc = await io.read(src);
  // clips: resample only (no restTracks / shortRotations: catclips.js fits every track to each
  // body, as the Hounds); wearables: unquantized, re-bound to the cat's own skeleton at run time
  if (kind === 'clips') await doc.transform(resample({ tolerance: 1e-4 }), MESHOPT);
  else if (kind === 'wear') await doc.transform(dedup(), PRUNE, MESHOPT);
  else await doc.transform(dedup(), PRUNE, quantize(QUANT), MESHOPT);
  write(dst, tidyJSON(await io.writeBinary(doc)));
}
function write(dst, data) {
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.writeFileSync(dst, data);
  bytes += data.length;
  files++;
}
const copy = (src, dst) => write(dst, fs.readFileSync(src));
const csv = f => fs.readFileSync(path.join(ROOT, f), 'utf8').trim().split('\n');

fs.rmSync(OUT, { recursive: true, force: true });
const bodies = csv('bodies.csv').slice(1).map(l => l.split(',')[0]);
const breeds = csv('breeds.csv').slice(1).map(l => l.split(',')).map(([slug, name, body, size]) => ({ slug, name, body, size }));

for (const b of bodies) await glb(path.join(ROOT, 'rigged', `${b}.glb`), path.join(OUT, 'cats', `${b}.glb`));
await glb(path.join(ROOT, 'rigged', 'clips.glb'), path.join(OUT, 'cats', 'cat-clips.glb'), 'clips');
console.log('cats');

const coats = JSON.parse(fs.readFileSync(path.join(ROOT, 'coats.json')));
for (const info of Object.values(coats)) {
  for (const m of info.masks) copy(path.join(ROOT, 'rigged', 'coats', m.file), path.join(OUT, 'cats', 'coats', m.file));
}
console.log('masks');

for (const f of fs.readdirSync(path.join(ROOT, 'rigged', 'wear')).filter(f => f.endsWith('.glb'))) {
  await glb(path.join(ROOT, 'rigged', 'wear', f), path.join(OUT, 'wear', f), 'wear');
}
copy(path.join(HOUNDS, 'rigged', 'wear', 'cloth.png'), path.join(OUT, 'wear', 'cloth-patterns.png'));
console.log('wear');

const props = csv('props/props.csv').slice(1).map(l => l.split(',')[0]);
for (const p of props) await glb(path.join(ROOT, 'props', 'models', `${p}.glb`), path.join(OUT, 'props', `${p}.glb`));
console.log('props');

// the data the helpers need, as a module: the library ships no JSON or CSV
const data = `// Chonky Cats data for catcoat.js and your game: generated by library.mjs.
// BREEDS: slug, name, body (the file in cats/) and size class. SIZES: the adult scale of each
// size class (a kitten is 0.3). COLOURWAYS: for each breed, the colourway that is that breed on
// its body. COATS: every body's coat masks, layers and colourways, for loadCoats(COATS, 'cats/coats/').
export const SIZES = { small: 0.45, medium: 0.55, large: 0.65 };
export const KITTEN = 0.3;
export const BODIES = ${JSON.stringify(bodies)};
export const BREEDS = ${JSON.stringify(breeds, null, 0).replaceAll('},{', '},\n  {').replace('[{', '[\n  {').replace('}]', '},\n]')};
export const COLOURWAYS = ${JSON.stringify(Object.fromEntries(Object.entries(coats).flatMap(([body, info]) =>
  info.colorways.filter(c => c.breed).map(c => [c.breed, c.slug]))))};
export const COATS = ${JSON.stringify(coats)};
`;
write(path.join(OUT, 'code', 'catdata.js'), Buffer.from(data));
// the Hounds' helpers, which play and colour the cats too (the same rig and coat system)
copy(path.join(HOUNDS, 'dogclips.js'), path.join(OUT, 'code', 'catclips.js'));
copy(path.join(HOUNDS, 'dogcoat.js'), path.join(OUT, 'code', 'catcoat.js'));

console.log(`${files} files, ${(bytes / 1048576).toFixed(1)} MB -> ${path.relative(process.cwd(), OUT)}`);
