// Library build: the pack as it ships in the RUN asset library, where a 3D pack's runtime
// files are its .glb files plus the .png / .jpg in or under a folder holding .glb files.
// So there are no KTX2 textures and no JSON here:
//   dogs/<breed>.glb, dogs/dog-clips.glb, dogs/coats/*.png   the dogs, every clip, coat masks
//   wear/<breed>--collar.glb, --bandana.glb, bandana-patterns.png
//   props/<prop>.glb
//   code/dogclips.js, dogcoat.js, dogdata.js                 copied into the game's source
// Geometry is quantized + meshopt (as the mobile build); textures stay the source JPEGs, so
// three's GLTFLoader with the meshopt decoder reads every file.
//
//   cd tools && npm run library      (writes ../library/)
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { dedup, prune, quantize, resample, meshopt } from '@gltf-transform/functions';
import { MeshoptEncoder, MeshoptDecoder } from 'meshoptimizer';
import { tidyJSON } from '../../../glb-tidy.mjs';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'library');

await MeshoptEncoder.ready;
await MeshoptDecoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({
  'meshopt.encoder': MeshoptEncoder, 'meshopt.decoder': MeshoptDecoder });
// as ktx2.mjs: 16-bit skin weights (8-bit flattens the tails), prune keeps the clip skin
const QUANT = { quantizePosition: 14, quantizeNormal: 8, quantizeTexcoord: 12, quantizeWeight: 16 };
const PRUNE = prune({ keepAttributes: true, keepExtras: true, propertyTypes: ['node', 'mesh', 'primitive', 'material', 'texture', 'accessor', 'bufferView'] });
const MESHOPT = meshopt({ encoder: MeshoptEncoder, level: 'medium', ...QUANT });
let bytes = 0, files = 0;

async function glb(src, dst, kind = 'model') {
  const doc = await io.read(src);
  // clips: resample only (pruning would drop the mesh-less skin the rest pose comes from);
  // wearables: unquantized, they are re-bound to the dog's own skeleton at run time
  if (kind === 'clips') {
    // no restTracks() or shortRotations() (glb-tidy.mjs): dogclips.js fits every track to each
    // dog (leg and neck counter-rotations for long bodies), so a track at the Labrador's rest
    // pose still moves on other dogs, and 16-bit rotations drift up to ~1 degree once fitted
    await doc.transform(resample({ tolerance: 1e-4 }));
    await doc.transform(MESHOPT);
  }
  else if (kind === 'wear') await doc.transform(dedup(), PRUNE, MESHOPT);
  else await doc.transform(dedup(), PRUNE, quantize(QUANT), MESHOPT);
  write(dst, tidyJSON(await io.writeBinary(doc)));
}
function write(dst, data) {
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.writeFileSync(dst, data);
  bytes += data.length;
  files++;
}
const copy = (src, dst) => write(dst, fs.readFileSync(src));

fs.rmSync(OUT, { recursive: true, force: true });
const breeds = fs.readFileSync(path.join(ROOT, 'breeds.csv'), 'utf8').trim().split('\n').slice(1)
  .map(l => l.split(',')).map(([slug, name, size]) => ({ slug, name, size }));

for (const b of breeds) await glb(path.join(ROOT, 'rigged', `${b.slug}.glb`), path.join(OUT, 'dogs', `${b.slug}.glb`));
await glb(path.join(ROOT, 'rigged', 'clips.glb'), path.join(OUT, 'dogs', 'dog-clips.glb'), 'clips');
console.log('dogs');

const coats = JSON.parse(fs.readFileSync(path.join(ROOT, 'coats.json')));
for (const info of Object.values(coats)) {
  for (const m of info.masks) copy(path.join(ROOT, 'rigged', 'coats', m.file), path.join(OUT, 'dogs', 'coats', m.file));
}
console.log('masks');

for (const f of fs.readdirSync(path.join(ROOT, 'rigged', 'wear')).filter(f => f.endsWith('.glb'))) {
  await glb(path.join(ROOT, 'rigged', 'wear', f), path.join(OUT, 'wear', f), 'wear');
}
copy(path.join(ROOT, 'rigged', 'wear', 'cloth.png'), path.join(OUT, 'wear', 'bandana-patterns.png'));
console.log('wear');

for (const f of fs.readdirSync(path.join(ROOT, 'props', 'models')).filter(f => f.endsWith('.glb'))) {
  await glb(path.join(ROOT, 'props', 'models', f), path.join(OUT, 'props', f));
}
console.log('props');

// the data the helpers need, as a module: the library ships no JSON or CSV
const data = `// Chonky Hounds data for dogcoat.js and your game: generated by tools/library.mjs.
// BREEDS: slug (the file name in dogs/), name and size class. SIZES: the adult scale of each
// size class (a puppy is 0.45). COATS: every breed's coat masks, layers and colourways, for
// loadCoats(COATS, 'dogs/coats/').
export const SIZES = { toy: 0.45, small: 0.65, medium: 0.85, large: 1.1 };
export const PUPPY = 0.45;
export const BREEDS = ${JSON.stringify(breeds, null, 0).replaceAll('},{', '},\n  {').replace('[{', '[\n  {').replace('}]', '},\n]')};
export const COATS = ${JSON.stringify(coats)};
`;
write(path.join(OUT, 'code', 'dogdata.js'), Buffer.from(data));
for (const f of ['dogclips.js', 'dogcoat.js']) copy(path.join(ROOT, f), path.join(OUT, 'code', f));

console.log(`${files} files, ${(bytes / 1048576).toFixed(1)} MB -> ${path.relative(process.cwd(), OUT)}`);
