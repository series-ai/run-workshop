def ground_death(model):
    slug = model.id.removeprefix("space-creatures-")
    heights = DEATH_HEIGHTS[slug]
    death = next(clip for clip in model.clips if clip.name == "death")
    part = "shell" if slug == "astro-crab" else "body"
    death.keys[part]["loc"] = [(i / 64, (0.0, y, 0.0)) for i, y in enumerate(heights)]
    return model
